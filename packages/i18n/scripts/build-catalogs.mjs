const locales = ['en', 'ar-IQ', 'ckb-IQ'];
let written = 0;
for (const [namespace, entries] of Object.entries(catalog)) {
  for (const locale of locales) {
    const out = {};
    for (const [key, translations] of Object.entries(entries)) {
      const value = translations[locale];
      if (value === undefined) throw new Error(`${namespace}.${key} has no ${locale} translation`);
      out[key] = value;
    }
    const dir = join(root, 'locales', locale);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, `${namespace}.json`), `${JSON.stringify(out, null, 2)}\n`);
    written += 1;
  }
}
console.log(`wrote ${written} catalog files, ${Object.keys(catalog).length} namespaces x ${locales.length} locales`);
